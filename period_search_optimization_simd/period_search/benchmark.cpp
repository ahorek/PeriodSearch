// compareVectors
bool compare_matrices(const std::vector<std::vector<int>> &expected,
					  const std::vector<std::vector<int>> &actual)
{
	if (expected.size() != actual.size() ||
		expected.empty() ||
		expected[0].size() != actual[0].size())
	{
		return false;
	}

	const size_t rows = expected.size();
	const size_t cols = expected[0].size();

	for (size_t row = 0; row < rows; ++row)
	{
		for (size_t col = 0; col < cols; ++col)
		{
			if (actual[row][col] != expected[row][col])
			{
				return false;
			}
		}
	}

	return true;
}

